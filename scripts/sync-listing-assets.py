#!/usr/bin/env python3
"""Render public listing assets from server.json; never query or publish anything."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    server = json.loads((ROOT / 'server.json').read_text())
    meta = server['_meta']['io.modelcontextprotocol.registry/publisher-provided']
    endpoint = server['remotes'][0]['url']
    manifest = {
        'identifier': 'infinite-audience',
        'name': server['title'],
        'version': server['version'],
        'description': server['description'],
        'author': meta['publisherName'],
        'authorUrl': 'https://github.com/no-fait',
        'homepage': meta['documentationUrl'],
        'cloudEndpoint': endpoint,
        'icon': server['icons'][0]['src'],
        'tags': ['identity-resolution', 'data-enrichment', 'audiences', 'marketing'],
    }
    listing = f"""<!-- Generated by scripts/sync-listing-assets.py from server.json. Edit the source, not this file. -->
# {server['title']}

{server['description']}

## Listing information

| Item | Value |
| --- | --- |
| Publisher | {meta['publisherName']} |
| Product | {meta['productWebsiteUrl']} |
| Documentation | {meta['documentationUrl']} |
| Repository | {meta['distributionRepositoryUrl']} |
| MCP endpoint | `{endpoint}` |
| Transport | Streamable HTTP |
| Registry identity | `{server['name']}` |
| Icon | {server['icons'][0]['src']} |
| Support | {meta['supportUrl']} |
| Support email | {meta['contactEmail']} |
| Privacy | {meta['privacyPolicyUrl']} |
| Service terms | {meta['termsOfServiceUrl']} |

## Capabilities and access

Infinite Audience brings identity resolution, customer data enrichment, and audience discovery into your AI workspace. Connect customer records to identities, enrich strong matches with chosen attributes, explore audience populations, compose segments and audiences, and prepare activation through supported destinations. Matching results depend on the supplied records and available data.

An Infinite Audience account, organization access, and appropriate OAuth scopes are required for execution. Public MCP discovery exposes tool definitions without authentication; all tool calls require authentication. Scope-filtered tool definitions are refreshed after sign-in. The [connection guide]({meta['documentationUrl']}) describes authentication and subscription capacity. The live tool catalog defines currently available capabilities and limitations.

## Skill installation

```sh
npx skills add no-fait/infinite-audience-mcp --skill infinite-audience
```

Installing the skill adds workflow instructions. Configure and authenticate the MCP connection separately using the connection guide. The skill does not bundle credentials or grant access to data.
"""
    return {
        'lhm.plugin.json': json.dumps(manifest, indent=2) + '\n',
        'docs/listing-assets.md': listing,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail when generated assets differ')
    args = parser.parse_args()
    stale = []
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit('Listing assets drift: ' + ', '.join(stale) + '. Run python3 scripts/sync-listing-assets.py')
    print('PASS: listing assets match server.json' if args.check else 'Updated public listing assets')


if __name__ == '__main__':
    main()
